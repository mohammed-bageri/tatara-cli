import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { x } from "tinyexec";
import { glob } from "tinyglobby";
import { loadProject, type Project } from "../project/config.ts";

const HEADER = "// Generated by `tatara sync` — do not edit.\n";

/** src/modules/notes/routes/note.routes.ts → #modules/notes/routes/note.routes */
export function specifier(path: string): string {
	return `#${path.replace(/^src\//, "").replace(/\.ts$/, "")}`;
}

function identifier(path: string, prefix: string): string {
	const parts = path
		.replace(/^src\//, "")
		.replace(/\.ts$/, "")
		.split("/")
		.filter(
			(p) => !["routes", "commands", "consumers", "schedules", "permissions", "db"].includes(p),
		);
	const raw = `${prefix}_${parts.join("_")}`.replace(/[^A-Za-z0-9_]/g, "_");
	return raw.replace(/_+/g, "_");
}

async function find(root: string, patterns: string[]): Promise<string[]> {
	const files = await glob(patterns, { cwd: root, ignore: ["**/*.test.ts", "**/*.d.ts"] });
	// core before modules, then alphabetical: stable output
	return files.sort((a, b) => {
		const rank = (p: string) => (p.startsWith("src/core/") ? 0 : 1);
		return rank(a) - rank(b) || a.localeCompare(b);
	});
}

function listModule(
	files: string[],
	options: { prefix: string; typeImport: string; typeName: string; exportName: string },
): string {
	const imports = files.map(
		(f) => `import ${identifier(f, options.prefix)} from "${specifier(f)}";`,
	);
	const names = files.map((f) => identifier(f, options.prefix));
	return `${HEADER}${options.typeImport}
${imports.join("\n")}${imports.length ? "\n" : ""}
export const ${options.exportName}: ${options.typeName}[] = [${names.join(", ")}];
`;
}

export interface SyncResult {
	written: string[];
}

async function writeIfChanged(path: string, content: string, written: string[]) {
	const current = existsSync(path) ? await readFile(path, "utf8") : undefined;
	if (current !== content) {
		await writeFile(path, content);
		written.push(path);
	}
}

export async function sync(project: Project = loadProject()): Promise<SyncResult> {
	const { root } = project;
	const out = join(root, "src/generated");
	await mkdir(out, { recursive: true });
	const written: string[] = [];
	const dirs = ["src/core/*", "src/modules/*"];

	const routes = await find(
		root,
		dirs.map((d) => `${d}/routes/*.routes.ts`),
	);
	await writeIfChanged(
		join(out, "routes.ts"),
		listModule(routes, {
			prefix: "routes",
			typeImport: 'import type { RouteDefinition } from "#core/http/routes";',
			typeName: "RouteDefinition",
			exportName: "routes",
		}),
		written,
	);

	const commands = await find(
		root,
		dirs.map((d) => `${d}/commands/*.ts`),
	);
	await writeIfChanged(
		join(out, "commands.ts"),
		listModule(commands, {
			prefix: "command",
			typeImport: 'import type { CommandDefinition } from "#core/commands/define";',
			typeName: "CommandDefinition",
			exportName: "commands",
		}),
		written,
	);

	if (project.has("jobs")) {
		const consumers = await find(
			root,
			dirs.map((d) => `${d}/consumers/*.ts`),
		);
		await writeIfChanged(
			join(out, "consumers.ts"),
			listModule(consumers, {
				prefix: "consumer",
				typeImport: 'import type { ConsumerDefinition } from "#core/jobs/define";',
				typeName: "ConsumerDefinition",
				exportName: "consumers",
			}),
			written,
		);
		const schedules = await find(
			root,
			dirs.map((d) => `${d}/schedules/*.ts`),
		);
		await writeIfChanged(
			join(out, "schedules.ts"),
			listModule(schedules, {
				prefix: "schedule",
				typeImport: 'import type { ScheduleDefinition } from "#core/jobs/define";',
				typeName: "ScheduleDefinition",
				exportName: "schedules",
			}),
			written,
		);
	}

	if (project.has("authz")) {
		const permissions = await find(root, ["src/modules/*/permissions/index.ts"]);
		const imports = permissions.map(
			(f) => `import ${identifier(f, "permissions")} from "${specifier(f)}";`,
		);
		const names = permissions.map((f) => identifier(f, "permissions"));
		await writeIfChanged(
			join(out, "permissions.ts"),
			`${HEADER}import { mergeCatalogs } from "#core/authz/catalog";
import corePermissions from "#core/authz/permissions";
${imports.join("\n")}${imports.length ? "\n" : ""}
export const catalog = mergeCatalogs(corePermissions${names.map((n) => `, ${n}`).join("")});
export type PermissionKey = (typeof catalog.keys)[number];
`,
			written,
		);
	}

	if (project.config.database !== "none") {
		const seeds = await find(
			root,
			dirs.map((d) => `${d}/db/seed.ts`),
		);
		await writeIfChanged(
			join(out, "seeds.ts"),
			listModule(seeds, {
				prefix: "seed",
				typeImport: 'import type { SeedDefinition } from "#core/db/seed";',
				typeName: "SeedDefinition",
				exportName: "seeds",
			}),
			written,
		);
	}

	if (project.config.orm === "drizzle") {
		const schemas = await find(
			root,
			dirs.map((d) => `${d}/db/*.schema.ts`),
		);
		await writeIfChanged(
			join(out, "schema.ts"),
			`${HEADER}${schemas.map((f) => `export * from "${specifier(f)}";`).join("\n")}\nexport {};\n`,
			written,
		);
	}

	if (project.config.orm === "prisma") {
		const bin = join(root, "node_modules/.bin/prisma");
		if (existsSync(bin)) {
			const result = await x(bin, ["generate"], {
				nodeOptions: { cwd: root },
				throwOnError: false,
			});
			if (result.exitCode !== 0) {
				throw new Error(`prisma generate failed:\n${result.stdout}${result.stderr}`);
			}
			written.push(join(out, "prisma"));
		}
	}

	return { written };
}
