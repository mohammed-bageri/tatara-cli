import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { x } from "tinyexec";
import { glob } from "tinyglobby";
import { loadProject, type Project } from "../project/config.ts";
import { ejectedPackages, pointAtEjected } from "../project/ejected.ts";

const HEADER = "// Generated by `tatara sync` — do not edit.\n";

/** src/modules/notes/routes/note.routes.ts → #modules/notes/routes/note.routes */
export function specifier(path: string): string {
	return `#${path.replace(/^src\//, "").replace(/\.ts$/, "")}`;
}

function identifier(path: string, prefix: string): string {
	const parts = path
		.replace(/^src\//, "")
		.replace(/\.ts$/, "")
		.split("/")
		.filter(
			(p) =>
				![
					"routes",
					"commands",
					"consumers",
					"schedules",
					"permissions",
					"db",
					"emails",
					"notifications",
				].includes(p),
		);
	const raw = `${prefix}_${parts.join("_")}`.replace(/[^A-Za-z0-9_]/g, "_");
	return raw.replace(/_+/g, "_");
}

async function find(root: string, patterns: string[]): Promise<string[]> {
	const files = await glob(patterns, { cwd: root, ignore: ["**/*.test.ts", "**/*.d.ts"] });
	// core before modules, then alphabetical: stable output
	return files.sort((a, b) => {
		const rank = (p: string) => (p.startsWith("src/core/") ? 0 : 1);
		return rank(a) - rank(b) || a.localeCompare(b);
	});
}

function listModule(
	files: string[],
	options: { prefix: string; typeImport: string; typeName: string; exportName: string },
): string {
	const imports = files.map(
		(f) => `import ${identifier(f, options.prefix)} from "${specifier(f)}";`,
	);
	const names = files.map((f) => identifier(f, options.prefix));
	return `${HEADER}${options.typeImport}
${imports.join("\n")}${imports.length ? "\n" : ""}
export const ${options.exportName}: ${options.typeName}[] = [${names.join(", ")}];
`;
}

/** The consumers keep their literal topics and schemas, so `TopicsOf<typeof consumers>` types enqueue. */
function consumerList(files: string[]): string {
	const imports = files.map((f) => `import ${identifier(f, "consumer")} from "${specifier(f)}";`);
	const names = files.map((f) => identifier(f, "consumer"));
	return `${HEADER}import type { ConsumerDefinition } from "@tatara/jobs";
${imports.join("\n")}${imports.length ? "\n" : ""}
// biome-ignore lint/suspicious/noExplicitAny: every consumer, whatever its payload
export const consumers = [${names.join(", ")}] as const satisfies readonly ConsumerDefinition<string, any>[];
`;
}

/** A convention folder's default exports, with their literal names kept for typed lookups. */
function definitionList(
	files: string[],
	prefix: string,
	pkg: string,
	typeName: string,
	exportName: string,
): string {
	const imports = files.map((f) => `import ${identifier(f, prefix)} from "${specifier(f)}";`);
	const names = files.map((f) => identifier(f, prefix));
	return `${HEADER}import type { ${typeName} } from "${pkg}";
${imports.join("\n")}${imports.length ? "\n" : ""}
// biome-ignore lint/suspicious/noExplicitAny: every definition, whatever its data
export const ${exportName} = [${names.join(", ")}] as const satisfies readonly ${typeName}<string, any>[];
`;
}

/** A command or seed factory a @tatara/* package declares in its package.json "tatara" field. */
interface Contribution {
	import: string;
	factory: string;
	/** argument name → the app module that exports it */
	args: Record<string, string>;
}

type ContributionKind = "commands" | "seeds";

/** What the app's installed (or ejected) @tatara/* packages contribute, by package name. */
async function contributions(project: Project, kind: ContributionKind): Promise<Contribution[]> {
	const pkg = JSON.parse(await readFile(join(project.root, "package.json"), "utf8")) as {
		dependencies?: Record<string, string>;
		devDependencies?: Record<string, string>;
	};
	const ejected = ejectedPackages(project.config);
	const names = [
		...Object.keys({ ...pkg.dependencies, ...pkg.devDependencies })
			.filter((n) => n.startsWith("@tatara/"))
			.map((n) => n.slice("@tatara/".length)),
		...ejected,
	];
	const out: Contribution[] = [];
	for (const name of [...new Set(names)].sort()) {
		// eject keeps the manifest next to the copy
		const file = ejected.includes(name)
			? join(project.root, "src/ejected", name, "tatara-package.json")
			: join(project.root, "node_modules/@tatara", name, "package.json");
		if (!existsSync(file)) continue;
		const json = JSON.parse(await readFile(file, "utf8")) as {
			tatara?: Partial<Record<ContributionKind, Contribution[]>>;
		} & Partial<Record<ContributionKind, Contribution[]>>;
		out.push(...((ejected.includes(name) ? json[kind] : json.tatara?.[kind]) ?? []));
	}
	return out;
}

/**
 * Like listModule, plus the packages' factories: `own` are the app's files, and an own entry wins
 * over a package's entry with the same name.
 */
function listWithPackages(
	files: string[],
	from: Contribution[],
	options: { prefix: string; typeImport: string; typeName: string; exportName: string },
): string {
	if (from.length === 0) return listModule(files, options);
	const imports = new Map<string, string>();
	const bind = (name: string, spec: string) => {
		const existing = imports.get(name);
		if (existing && existing !== spec)
			throw new Error(`tatara packages need "${name}" from both ${existing} and ${spec}`);
		imports.set(name, spec);
	};
	for (const c of from) {
		bind(c.factory, c.import);
		for (const [arg, spec] of Object.entries(c.args)) bind(arg, spec);
	}
	const named = [...imports].map(([name, spec]) => `import { ${name} } from "${spec}";`);
	const own = files.map((f) => `import ${identifier(f, options.prefix)} from "${specifier(f)}";`);
	const calls = from.map((c) => `...${c.factory}({ ${Object.keys(c.args).join(", ")} })`);
	const t = options.typeName;
	return `${HEADER}${options.typeImport}
${[...named, ...own].join("\n")}

const own: ${t}[] = [${files.map((f) => identifier(f, options.prefix)).join(", ")}];
// from the installed @tatara/* packages; the app's own entry of the same name wins
const fromPackages: ${t}[] = [${calls.join(", ")}];
export const ${options.exportName}: ${t}[] = [
	...own,
	...fromPackages.filter((c) => !own.some((o) => o.name === c.name)),
];
`;
}

export interface SyncResult {
	written: string[];
}

async function writeIfChanged(path: string, content: string, written: string[]) {
	const current = existsSync(path) ? await readFile(path, "utf8") : undefined;
	if (current !== content) {
		await writeFile(path, content);
		written.push(path);
	}
}

export async function sync(project: Project = loadProject()): Promise<SyncResult> {
	const { root } = project;
	const ejected = ejectedPackages(project.config);
	// generated files import ejected packages from the app's copy
	const write = (path: string, content: string, out: string[]) =>
		writeIfChanged(path, pointAtEjected(content, ejected), out);
	const out = join(root, "src/generated");
	await mkdir(out, { recursive: true });
	const written: string[] = [];
	const dirs = ["src/core/*", "src/modules/*"];

	const routes = await find(
		root,
		dirs.map((d) => `${d}/routes/*.routes.ts`),
	);
	await write(
		join(out, "routes.ts"),
		listModule(routes, {
			prefix: "routes",
			typeImport: 'import type { RouteDefinition } from "#core/http/routes";',
			typeName: "RouteDefinition",
			exportName: "routes",
		}),
		written,
	);

	const commands = await find(
		root,
		dirs.map((d) => `${d}/commands/*.ts`),
	);
	await write(
		join(out, "commands.ts"),
		listWithPackages(commands, await contributions(project, "commands"), {
			prefix: "command",
			typeImport: 'import type { CommandDefinition } from "@tatara/core";',
			typeName: "CommandDefinition",
			exportName: "commands",
		}),
		written,
	);

	if (project.has("jobs")) {
		const consumers = await find(
			root,
			dirs.map((d) => `${d}/consumers/*.ts`),
		);
		await write(join(out, "consumers.ts"), consumerList(consumers), written);
		const schedules = await find(
			root,
			dirs.map((d) => `${d}/schedules/*.ts`),
		);
		await write(
			join(out, "schedules.ts"),
			listModule(schedules, {
				prefix: "schedule",
				typeImport: 'import type { ScheduleDefinition } from "@tatara/jobs";',
				typeName: "ScheduleDefinition",
				exportName: "schedules",
			}),
			written,
		);
	}

	if (project.has("email")) {
		const emails = await find(root, ["src/modules/*/emails/*.ts"]);
		await write(
			join(out, "emails.ts"),
			definitionList(emails, "email", "@tatara/email", "EmailDefinition", "emails"),
			written,
		);
	}

	if (project.has("notifications")) {
		const notifications = await find(root, ["src/modules/*/notifications/*.ts"]);
		await write(
			join(out, "notifications.ts"),
			definitionList(
				notifications,
				"notification",
				"@tatara/notifications",
				"NotificationDefinition",
				"notifications",
			),
			written,
		);
	}

	if (project.has("authz")) {
		const permissions = await find(root, ["src/modules/*/permissions/*.permissions.ts"]);
		const imports = permissions.map(
			(f) => `import ${identifier(f, "permissions")} from "${specifier(f)}";`,
		);
		const names = permissions.map((f) => identifier(f, "permissions"));
		await write(
			join(out, "permissions.ts"),
			`${HEADER}import { authzPermissions, mergeCatalogs, type PermissionKeysOf } from "@tatara/authz";
${imports.join("\n")}${imports.length ? "\n" : ""}
export const catalog = mergeCatalogs(authzPermissions${names.map((n) => `, ${n}`).join("")});

export type PermissionKey =
	| PermissionKeysOf<typeof authzPermissions>${names.map((n) => `\n\t| PermissionKeysOf<typeof ${n}>`).join("")};
`,
			written,
		);
	}

	if (project.config.database !== "none") {
		const seeds = await find(
			root,
			dirs.map((d) => `${d}/db/seed.ts`),
		);
		await write(
			join(out, "seeds.ts"),
			listWithPackages(seeds, await contributions(project, "seeds"), {
				prefix: "seed",
				typeImport: 'import type { SeedDefinition } from "@tatara/db";',
				typeName: "SeedDefinition",
				exportName: "seeds",
			}),
			written,
		);
	}

	if (project.config.orm === "drizzle") {
		const schemas = await find(
			root,
			dirs.map((d) => `${d}/db/*.schema.ts`),
		);
		await write(
			join(out, "schema.ts"),
			`${HEADER}${schemas.map((f) => `export * from "${specifier(f)}";`).join("\n")}\nexport {};\n`,
			written,
		);
	}

	if (project.config.orm === "prisma") {
		const bin = join(root, "node_modules/.bin/prisma");
		if (existsSync(bin)) {
			const result = await x(bin, ["generate"], {
				nodeOptions: { cwd: root },
				throwOnError: false,
			});
			if (result.exitCode !== 0) {
				throw new Error(`prisma generate failed:\n${result.stdout}${result.stderr}`);
			}
			written.push(join(out, "prisma"));
		}
	}

	return { written };
}
